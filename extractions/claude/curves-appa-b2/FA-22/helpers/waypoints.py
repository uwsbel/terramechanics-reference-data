def u_at(curve, v):
    """u of the waypoint polyline at row v (polyline is monotone in v); None outside it."""
    pts = sorted(curve, key=lambda p: p[1])
    if v < pts[0][1] or v > pts[-1][1]:
        return None
    for (u0, v0), (u1, v1) in zip(pts, pts[1:]):
        if v0 <= v <= v1:
            return u0 + (u1 - u0) * (v - v0) / (v1 - v0) if v1 > v0 else u0
